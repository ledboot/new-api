package billing_setting

import (
	"fmt"
	"math"
	"slices"
	"strconv"
	"strings"

	"github.com/expr-lang/expr/ast"
	"github.com/expr-lang/expr/parser"
	"github.com/shopspring/decimal"
)

// OpenLuxRoundedPrice retains the native group multiplier while freezing rounded
// unit prices into the existing expression/snapshot billing path.
type OpenLuxRoundedPrice struct {
	Expression        string
	SellingExpression string
	GroupRatio        float64
}

func RoundOpenLuxGroupRatio(value float64) (float64, error) {
	if math.IsNaN(value) || math.IsInf(value, 0) || value < 0 {
		return 0, fmt.Errorf("invalid OpenLux group multiplier")
	}
	result, _ := openLuxDecimal(value).RoundCeil(4).Float64()
	return result, nil
}

// OpenLuxPriceExpressions rounds each chargeable unit, before multiplying usage.
// Cost and stored model expressions stay untouched. Conditions and image quantity
// are never rounded. Only the canonical expressions generated by our importer
// are accepted, so an unsupported shape cannot silently receive a partial rule.
func OpenLuxPriceExpressions(expression string, groupRatio float64) (OpenLuxRoundedPrice, error) {
	ratio, err := RoundOpenLuxGroupRatio(groupRatio)
	if err != nil {
		return OpenLuxRoundedPrice{}, err
	}
	text := strings.TrimPrefix(expression, "v1:")
	result := OpenLuxRoundedPrice{GroupRatio: ratio}
	for _, normalized := range []bool{true, false} {
		tree, err := parser.Parse(text)
		if err != nil {
			return OpenLuxRoundedPrice{}, err
		}
		node, err := roundOpenLuxPriceNode(tree.Node, decimal.NewFromFloat(ratio), normalized)
		if err != nil {
			return OpenLuxRoundedPrice{}, err
		}
		if normalized {
			result.Expression = node.String()
		} else {
			result.SellingExpression = node.String()
		}
	}
	return result, nil
}

func roundOpenLuxPriceNode(node ast.Node, ratio decimal.Decimal, normalized bool) (ast.Node, error) {
	switch n := node.(type) {
	case *ast.ConditionalNode:
		var err error
		n.Exp1, err = roundOpenLuxPriceNode(n.Exp1, ratio, normalized)
		if err != nil {
			return nil, err
		}
		n.Exp2, err = roundOpenLuxPriceNode(n.Exp2, ratio, normalized)
		return n, err
	case *ast.CallNode:
		callee, ok := n.Callee.(*ast.IdentifierNode)
		if !ok {
			break
		}
		if callee.Value == "tier" && len(n.Arguments) == 2 {
			var err error
			n.Arguments[1], err = roundOpenLuxPriceNode(n.Arguments[1], ratio, normalized)
			return n, err
		}
		if callee.Value == "fixed" && len(n.Arguments) == 1 {
			var err error
			n.Arguments[0], err = roundedOpenLuxCoefficient(n.Arguments[0], ratio, normalized)
			return n, err
		}
	case *ast.BinaryNode:
		if n.Operator == "+" {
			var err error
			n.Left, err = roundOpenLuxPriceNode(n.Left, ratio, normalized)
			if err != nil {
				return nil, err
			}
			n.Right, err = roundOpenLuxPriceNode(n.Right, ratio, normalized)
			return n, err
		}
		if n.Operator == "*" {
			if variable, ok := n.Left.(*ast.IdentifierNode); ok && slices.Contains([]string{"p", "c", "cr", "cc", "cc1h", "cc12h", "img", "img_cr", "img_o", "ai", "ao"}, variable.Value) {
				var err error
				n.Right, err = roundedOpenLuxCoefficient(n.Right, ratio, normalized)
				return n, err
			}
			if quantity, ok := n.Right.(*ast.IdentifierNode); ok && quantity.Value == "image_count" {
				var err error
				n.Left, err = roundOpenLuxPriceNode(n.Left, ratio, normalized)
				return n, err
			}
		}
	}
	return nil, fmt.Errorf("unsupported OpenLux pricing expression")
}

func roundedOpenLuxCoefficient(node ast.Node, ratio decimal.Decimal, normalized bool) (ast.Node, error) {
	var value float64
	switch n := node.(type) {
	case *ast.IntegerNode:
		value = float64(n.Value)
	case *ast.FloatNode:
		value = n.Value
	default:
		return nil, fmt.Errorf("unsupported OpenLux price coefficient")
	}
	if math.IsNaN(value) || math.IsInf(value, 0) || value < 0 {
		return nil, fmt.Errorf("invalid OpenLux price coefficient")
	}
	price := openLuxDecimal(value).Mul(ratio).RoundCeil(4)
	if normalized && !ratio.IsZero() {
		price = price.DivRound(ratio, 32)
	}
	result, _ := price.Float64()
	if math.IsNaN(result) || math.IsInf(result, 0) {
		return nil, fmt.Errorf("OpenLux price exceeds supported range")
	}
	return &ast.FloatNode{Value: result}, nil
}

// Importer arithmetic can leave a few binary ULPs on an otherwise exact price.
// Remove only that noise; meaningful fifth/sixth digits and tiny prices survive.
func openLuxDecimal(value float64) decimal.Decimal {
	candidate, _ := strconv.ParseFloat(strconv.FormatFloat(value, 'g', 15, 64), 64)
	if math.Abs(candidate-value) <= math.Abs(value)*4*(math.Nextafter(1, 2)-1) {
		value = candidate
	}
	return decimal.NewFromFloat(value)
}
